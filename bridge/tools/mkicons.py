"""Render the bridge screen's activity icons from Symbols Nerd Font (Material Design
Icons, Apache 2.0) into 4-bit antialiased bitmaps, the same format as the fonts:
main/icons.h.

    python3 tools/mkicons.py SymbolsNerdFontMono-Regular.ttf 22
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ICONS = {"pointer": 0xF01C0, "tap": 0xF0741, "keys": 0xF030C, "robot": 0xF06A9}
src, px = sys.argv[1], int(sys.argv[2])
here = os.path.join(os.path.dirname(__file__), "..", "main")
font = ImageFont.truetype(src, px * 4)
out = [f"// Generated by tools/mkicons.py from {os.path.basename(src)} (Material Design Icons) at {px} px.",
       "#pragma once", '#include "display.h"']
for name, cp in ICONS.items():
    big = Image.new("L", (px * 8, px * 8), 0)
    ImageDraw.Draw(big).text((px * 2, px * 2), chr(cp), font=font, fill=255)
    big = big.crop(big.getbbox())
    s = px * 4 / max(big.size)  # fit the glyph's ink in the px x px square, centred
    big = big.resize((max(1, round(big.width * s)), max(1, round(big.height * s))), Image.LANCZOS)
    im = Image.new("L", (px * 4, px * 4), 0)
    im.paste(big, ((im.width - big.width) // 2, (im.height - big.height) // 2))
    im = im.resize((px, px), Image.LANCZOS)
    p4 = [v >> 4 for v in im.tobytes()]
    data = [p4[i] << 4 | (p4[i + 1] if i + 1 < len(p4) else 0) for i in range(0, len(p4), 2)]
    out.append(f"static const uint8_t icon_{name}_bits[] = {{")
    out += ["  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + "," for i in range(0, len(data), 24)]
    out.append("};")
    out.append(f"static const font_t icon_{name} = {{ {px}, {px}, {len(data)}, icon_{name}_bits }};")
open(os.path.join(here, "icons.h"), "w").write("\n".join(out) + "\n")
print("icons.h:", ", ".join(ICONS), px, "px")
